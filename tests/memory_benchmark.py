"""Offline, synthetic Japanese memory baseline. Run with uv run python tests/memory_benchmark.py.

Gold decisions are supplied, not generated by an AI. Only clock and synchronization
are substituted; saving, provenance validation, folding, audit and retrieval use
production code. This developer harness is not a security sandbox.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / 'tests' / 'fixtures' / 'memory_ja_v1.json'


def ranking_metrics(expected, retrieved, k):
    """Macro recall and reciprocal rank; negative queries have separate counters."""
    wanted = set(expected)
    if not wanted:
        return None
    top = retrieved[:k]
    return {'recall': len(wanted.intersection(top)) / len(wanted),
            'rr': next((1 / (i + 1) for i, item in enumerate(top) if item in wanted), 0.0)}


def validate_fixture(data):
    if not isinstance(data, dict) or type(data.get('version')) is not int or data['version'] != 1:
        raise ValueError('unsupported fixture version')
    if set(data) != {'version', 'id', 'now', 'turns', 'queries'}:
        raise ValueError('unknown fixture fields')
    seen = set()
    for turn in data['turns']:
        if (set(turn) != {'uuid', 'role', 'ts', 'text', 'rows'}
                or turn['role'] not in ('user', 'assistant')
                or not isinstance(turn['uuid'], str) or not turn['uuid']
                or turn['uuid'] in seen or not isinstance(turn['rows'], list)
                or (turn['role'] == 'assistant' and turn['rows'])):
            raise ValueError('invalid fixture turn')
        seen.add(turn['uuid'])
    seen = set()
    for query in data['queries']:
        if (set(query) != {'id', 'group', 'text', 'expected'}
                or query['id'] in seen or not isinstance(query['text'], str)
                or not isinstance(query['expected'], list)
                or any(not isinstance(key, str) for key in query['expected'])):
            raise ValueError('invalid fixture query')
        seen.add(query['id'])


def _context_keys(context):
    keys = {f'fact:{key}' for key, value in context.get('profile', {}).items() if value}
    if context.get('full_context'):
        life = context['life']
        keys.update(f'fact:{key}' for key, value in life.get('facts', {}).items() if value.get('note'))
        keys.update(f'interest:{key}' for key, value in life.get('interests', {}).items() if value.get('note'))
        keys.update(f'thread:{item["topic"]}' for item in life.get('open_threads', []) if item.get('note'))
    else:
        keys.update(f'{item["kind"]}:{item["topic"]}' for item in context['matches'] if item.get('note'))
        keys.update(f'thread:{item["topic"]}' for item in context['attention'] if item.get('note'))
    # Catalog titles alone do not count as supplying the memory's contents.
    return keys


def _evaluate(home, fixture, node):
    # Imports happen only after the temporary environment is installed.
    import watari_cli
    if Path(watari_cli.__file__).resolve().parent != ROOT / 'src/watari_cli':
        raise RuntimeError('benchmark must use this checkout, not an installed release')
    from watari_cli import memory_operations as ops
    from watari_cli.engine import audit, ingest, regen_state, watari_lib as wl

    fixed_now = wl.parse_ts(fixture['now'])
    messages = [{k: t[k] for k in ('uuid', 'role', 'ts', 'text')} | {
        'store': 'pi', 'session': 'synthetic-ja', 'cwd': '/workspace/synthetic',
        'machine': 'synthetic-pc', 'computer': 'linux', 'runtime': 'native',
    } for t in fixture['turns']]
    decisions = [{'uuid': t['uuid'], 'rows': t['rows']} for t in fixture['turns'] if t['role'] == 'user']
    checks = []

    def check(name, passed):
        checks.append({'id': name, 'passed': bool(passed)})

    for genre in ('life', 'learning'):
        (home / genre).mkdir(parents=True)
        (home / genre / 'log.jsonl').write_text('', encoding='utf-8')
    with (patch.object(wl, 'now_utc', lambda: fixed_now),
          patch.object(ingest, 'now_utc', lambda: fixed_now),
          patch.object(audit, 'now_utc', lambda: fixed_now),
          patch.object(regen_state, 'now_utc', lambda: fixed_now),
          patch.object(ops.git_sync, 'sync_after_write', lambda _home: None)):
        ingest.apply([])
        saves = []
        for message in messages:
            if message['role'] == 'user':
                decision = next(d for d in decisions if d['uuid'] == message['uuid'])
                saves.append(ops.save_batch(ops.current_batch(message), [decision]))
        check('save-checked', all(s['saved'] and s['checked'] and not s['warnings'] for s in saves))
        records = wl.load_log('life')
        selected = {(d['uuid'], r['kind']): r for d in decisions for r in d['rows']}
        check('selected-content-preserved', len(records) == len(selected) and all(
            {k: r[k] for k in ops.ROW_FIELDS if k in r} == selected.get((r['refs']['uuid'], r['kind']))
            for r in records))
        check('source-provenance', all(
            any(m['role'] == 'user' and m['uuid'] == r['refs']['uuid'] and m['ts'] == r['ts']
                and m['machine'] == r['refs']['machine'] for m in messages) for r in records))
        before = (home / 'life' / 'log.jsonl').read_bytes()
        snapshot = {'stores': {'pi': {'readable': True, 'cursor': None}}, 'messages': messages}
        batch = ops.make_batch(snapshot)
        forged = [{'uuid': 'a01', 'rows': decisions[0]['rows']}, *decisions[1:]]
        rejected = False
        try:
            ops.save_batch(batch, forged)
        except ValueError:
            rejected = True
        check('assistant-source-rejected', rejected and before == (home / 'life/log.jsonl').read_bytes())
        replay = ops.save_batch(ops.current_batch(messages[1]), [decisions[1]])
        check('replay-deduplicated', replay['checked'] and before == (home / 'life/log.jsonl').read_bytes())
        check('skipped-turn-absent', not any(r['refs']['uuid'] == 'u06' for r in records))
        states = {g: json.loads((home / g / 'state.json').read_text(encoding='utf-8')) for g in wl.GENRES}
        expected_states = regen_state.regen(now=fixed_now)
        check('regeneration-deterministic', states == expected_states == regen_state.regen(now=fixed_now))
        life = states['life']
        check('correction-current', life['facts']['delivery_destination']['note'] == decisions[1]['rows'][0]['note'])
        closed = ops.get_memory('thread', '試作冊子の校正')['rows']
        check('closed-task-history', [r['status'] for r in closed] == ['closed', 'open']
              and all(t['topic'] != '試作冊子の校正' for t in life['open_threads']))

        # Same file-loading helpers and performance options used by the actual Pi hook.
        child = subprocess.run([node, str(ROOT / 'tests/memory_benchmark.mjs')],
                               input=json.dumps(fixture['queries'], ensure_ascii=False),
                               capture_output=True, text=True, timeout=15, check=True)
        queries = json.loads(child.stdout)
        for query in queries:
            evidence = []
            for key in query['expected']:
                kind, topic = key.split(':', 1)
                evidence.extend(ops.get_memory(kind, topic)['rows'])
            query['evidence'] = evidence
            search_keys = [f'{item["kind"]}:{item["topic"]}' for item in query['search']]
            query['retrieved_evidence'] = {
                key: ops.get_memory(*key.split(':', 1))['rows'] for key in search_keys
            }
            query['scores'] = {'search': ranking_metrics(query['expected'], search_keys, 6)}
            for mode, context in query['contexts'].items():
                wanted = set(query['expected'])
                query['scores'][mode] = ({'recall': len(wanted & _context_keys(context)) / len(wanted)}
                                         if wanted else None)
        check('context-budgets', all(q['context_bytes']['fast'] <= 4_000
                                    and q['context_bytes']['balanced'] <= 16_000 for q in queries))
        approval = selected[('u08', 'fact')]['profile']['value']
        check('approval-preserved', life['profile']['approval_rule'] == approval and all(
            c['profile'].get('approval_rule') == approval for q in queries for c in q['contexts'].values()))
        check('closed-task-not-supplied', all('thread:試作冊子の校正' not in _context_keys(c)
                                            for q in queries for c in q['contexts'].values()))
        # Validity gates cover storage; retrieval misses remain visible measurements.
        check('expected-evidence-exists', all(q['evidence'] for q in queries if q['expected']))

    positives = [q for q in queries if q['expected']]
    metrics = {}
    for mode in ('search', 'fast', 'balanced', 'butler'):
        scores = [q['scores'][mode] for q in positives]
        metrics[mode] = {'queries': len(scores), 'recall': sum(s['recall'] for s in scores) / len(scores)}
        if mode == 'search':
            metrics[mode].update(k=6, mrr=sum(s['rr'] for s in scores) / len(scores))
    groups = {}
    for group in sorted({q['group'] for q in positives}):
        scores = [q['scores']['search'] for q in positives if q['group'] == group]
        groups[group] = {'queries': len(scores), 'recall': sum(s['recall'] for s in scores) / len(scores),
                         'mrr': sum(s['rr'] for s in scores) / len(scores)}
    negatives = [q for q in queries if not q['expected']]
    return {'version': 1, 'fixture': fixture['id'], 'fixed_now': fixture['now'],
            'checks': checks, 'metrics': metrics, 'search_by_group': groups, 'source_messages': messages,
            'negative_queries': {'queries': len(negatives),
                                 'search_false_positive_queries': sum(bool(q['search']) for q in negatives)},
            'records': [{k: v for k, v in r.items() if not k.startswith('_')} for r in records],
            'histories': {'proofreading': closed}, 'queries': queries,
            'not_measured': ['model_selection', 'answer_accuracy', 'synchronization', 'live_memory']}


def run_benchmark():
    """Own the temporary home; never accept a caller's memory path or credentials."""
    if any(name.startswith('watari_cli.') for name in sys.modules):
        raise RuntimeError('run the benchmark in a fresh process before loading memory modules')
    fixture = json.loads(FIXTURE.read_text(encoding='utf-8'))
    validate_fixture(fixture)
    node = shutil.which('node')
    if not node:
        raise RuntimeError('Node.js is required; no benchmark cases were run.')
    command = [node, str(ROOT / 'tests/memory_benchmark.mjs')]

    # Regression guard, not an OS sandbox: catch accidental Python networking or
    # additional subprocesses (including Git sync). The fixed JS helper is offline.
    def offline(event, args):
        if event in ('socket.connect', 'socket.getaddrinfo', 'socket.sendto'):
            raise RuntimeError('network is disabled in this benchmark')
        if event == 'subprocess.Popen' and args[1] != command:
            raise RuntimeError('unexpected subprocess in offline benchmark')
    sys.addaudithook(offline)
    with tempfile.TemporaryDirectory(prefix='watari-memory-baseline-') as tmp:
        root = Path(tmp)
        # Clear all inherited keys, model settings, Git and Node options, and stores.
        env = {'HOME': str(root / 'home'), 'WATARI_HOME': str(root / 'memory'),
               'XDG_CONFIG_HOME': str(root / 'config'), 'XDG_STATE_HOME': str(root / 'state'),
               'XDG_DATA_HOME': str(root / 'data'), 'WATARI_STORE_PI': str(root / 'pi'),
               'PYTHONDONTWRITEBYTECODE': '1', 'LANG': 'C.UTF-8'}
        with patch.dict(os.environ, env, clear=True):
            return _evaluate(root / 'memory', fixture, node)


def main():
    parser = argparse.ArgumentParser(description='架空の日本語会話で記憶の保存・訂正・検索を測定します。実際の記憶は使いません。')
    parser.add_argument('--json', action='store_true', help='出典とAIへ渡す内容を含む検証結果を出力')
    args = parser.parse_args()
    report = run_benchmark()
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        passed = sum(c['passed'] for c in report['checks'])
        print(f'架空の日本語会話による記憶テスト: {passed}/{len(report["checks"])}項目成功')
        search = report['metrics']['search']
        print(f'検索上位6件（{search["queries"]}問）: 期待する記憶の取得率 {search["recall"]:.1%} / MRR {search["mrr"]:.3f}')
        for group, score in report['search_by_group'].items():
            print(f'  {group}（{score["queries"]}問）: 取得率 {score["recall"]:.1%}')
        for mode in ('fast', 'balanced', 'butler'):
            print(f'{mode}: AIへ渡す内容に期待する記憶を含む割合 {report["metrics"][mode]["recall"]:.1%}')
        for q in report['queries']:
            if q['expected'] and q['scores']['search']['recall'] < 1:
                print(f'検索で未取得: {q["text"]}')
        negatives = report['negative_queries']
        print(f'該当なしを期待する質問への検索候補あり: {negatives["search_false_positive_queries"]}/{negatives["queries"]}件')
        for check in report['checks']:
            if not check['passed']:
                print(f'失敗項目: {check["id"]}')
        print('AIによる選別・回答の正確さ、同期、実際の記憶は未検証です。')
    return 0 if all(c['passed'] for c in report['checks']) else 1


if __name__ == '__main__':
    raise SystemExit(main())
